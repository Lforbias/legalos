import { expect, test } from "@playwright/test";
import { PDFDocument } from "pdf-lib";
test("BOX: intimação até tarefa, prazo validado, documento e acervo", async ({ page }) => {
  test.setTimeout(120_000);
  const id = Math.random().toString(36).slice(2, 10);
  await page.goto("/register");
  await page.getByLabel("Nome completo").fill(`Responsável fluxo ${id}`);
  await page.getByLabel("E-mail").fill(`box-fluxo-${id}@example.test`);
  await page.getByLabel("Senha", { exact: true }).fill("SenhaForte123");
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await page.getByLabel("Nome do escritório").fill(`Fluxo BOX ${id}`);
  await page.getByRole("button", { name: "Criar escritório", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Olá/ })).toBeVisible();
  await page.goto("/processos/novo");
  await page.getByLabel("Título do processo").fill(`Processo fluxo ${id}`);
  await page.getByRole("button", { name: "Cadastrar processo", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Processo fluxo ${id}`, exact: true })).toBeVisible();
  const caseUrl = page.url().split("?")[0]!;
  await page.goto("/caixa-de-entrada/nova");
  await page.getByLabel("Título", { exact: true }).fill(`Intimação fluxo ${id}`);
  await page.getByLabel("Texto", { exact: true }).fill(`Conteúdo fictício de intimação para teste ${id}.`);
  await page.getByLabel("Data de recebimento").fill("2026-10-23");
  await page.getByLabel("Vincular ao processo", { exact: true }).selectOption({ label: `Processo fluxo ${id}` });
  await page.getByRole("button", { name: "Registrar intimação", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Intimação fluxo ${id}`, exact: true })).toBeVisible();
  const noticeUrl = page.url();
  await page.getByRole("link", { name: "Criar tarefa", exact: true }).click();
  await page.getByLabel("Título", { exact: true }).fill(`Providência fluxo ${id}`);
  await page.getByRole("button", { name: "Criar tarefa", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Providência fluxo ${id}`, exact: true })).toBeVisible();
  await page.getByLabel("Situação da tarefa", { exact: true }).selectOption("DONE");
  await expect(page.getByLabel("Situação da tarefa", { exact: true })).toHaveValue("DONE");
  await page.goto(noticeUrl);
  await expect(page.getByRole("link", { name: `Providência fluxo ${id}`, exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Cadastrar prazo", exact: true }).click();
  await page.getByLabel("Título", { exact: true }).fill(`Prazo fluxo ${id}`);
  await page.getByLabel("Data fatal", { exact: true }).fill("2030-05-13");
  await page.getByRole("button", { name: "Cadastrar prazo", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Prazo fluxo ${id}`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Validar prazo", exact: true }).click();
  await expect(page.getByText("Validado", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Marcar como cumprido", exact: true }).click();
  await expect(page.getByText("Cumprido", { exact: true }).first()).toBeVisible();
  await page.goto(`${caseUrl}?aba=documentos`);
  const pdf = await PDFDocument.create(); pdf.addPage();
  await page.locator("#document-file").setInputFiles({ name: `peca-fluxo-${id}.pdf`, mimeType: "application/pdf", buffer: Buffer.from(await pdf.save()) });
  await expect(page.getByRole("link", { name: `peca-fluxo-${id}.pdf`, exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Autos digitais", exact: true }).click();
  await expect(page.getByRole("region", { name: "Fila de download dos autos" })).toContainText("Nenhum download em fila.");
  await expect(page.getByRole("button", { name: "Baixar todos os autos", exact: true })).toHaveCount(0);
  await expect(page.locator("iframe")).toBeVisible();
  await page.goto(noticeUrl);
  await expect(page.getByRole("link", { name: `Prazo fluxo ${id}`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Marcar como tratada", exact: true }).click();
  await expect(page.getByText("Tratada", { exact: true }).first()).toBeVisible();
  await page.goto("/caixa-de-entrada?caixa=acervo");
  await expect(page.getByRole("link", { name: `Intimação fluxo ${id}`, exact: true })).toBeVisible();
});

test("Autos: fila aparece após navegar e permite retomar uma falha", async ({ page }) => {
  const { Client } = await import("pg");
  const databaseUrl = process.env.TEST_DATABASE_URL ?? "postgresql://legalos:legalos_dev@localhost:5432/legalos_test";
  if (!/test/i.test(new URL(databaseUrl).pathname)) throw Error("Fixture exige banco de testes");
  const client = new Client({ connectionString: databaseUrl });
  await client.connect();
  try {
    const id = Math.random().toString(36).slice(2, 10), email = `fila-ui-${id}@example.test`;
    await page.goto("/register");
    await page.getByLabel("Nome completo").fill(`Responsável fila ${id}`);
    await page.getByLabel("E-mail").fill(email);
    await page.getByLabel("Senha", { exact: true }).fill("SenhaForte123");
    await page.getByRole("button", { name: "Criar conta", exact: true }).click();
    await page.getByLabel("Nome do escritório").fill(`Fila ${id}`);
    await page.getByRole("button", { name: "Criar escritório", exact: true }).click();
    await expect(page.getByRole("heading", { name: /Olá/ })).toBeVisible();
    await page.goto("/processos/novo");
    await page.getByLabel("Título do processo").fill(`Fila UI ${id}`);
    await page.getByRole("button", { name: "Cadastrar processo", exact: true }).click();
    await expect(page.getByRole("heading", { name: `Fila UI ${id}`, exact: true })).toBeVisible();
    const caseId = page.url().split("/processos/")[1]!.split("?")[0]!;
    // Somente fixture de interface: nenhum acesso externo é feito com essa conexão.
    const { rows } = await client.query('SELECT organization_id FROM cases WHERE id = $1', [caseId]);
    await client.query('UPDATE cases SET number = $1 WHERE id = $2', ["0001234-17.2024.5.05.0001", caseId]);
    await client.query('INSERT INTO court_connections (id, organization_id, label, jtr, endpoint_url, auth_mode, secret_enc, updated_at) VALUES ($1,$2,$3,$4,$5,$6,$7,NOW())', [crypto.randomUUID(), rows[0].organization_id, "Tribunal fictício UI", "5.05", "https://example.test/ws", "PASSWORD", "fixture-sem-credencial"]);
    await page.goto(`/processos/${caseId}/autos`);
    await page.getByRole("button", { name: "Baixar todos os autos", exact: true }).click();
    const queue = page.getByRole("region", { name: "Fila de download dos autos" });
    await expect(queue).toContainText("Na fila");
    await page.goto("/box"); await page.goto(`/processos/${caseId}/autos`);
    await expect(queue).toContainText("Na fila");
    await expect(page.getByRole("button", { name: "Baixar todos os autos", exact: true })).toBeDisabled();
    await client.query("UPDATE autos_download_jobs SET status = 'FAILED', attempts = 3, listed = 60, imported = 25, remaining = 35, skipped = 2, error = 'Falha simulada na fixture' WHERE case_id = $1", [caseId]);
    await page.reload();
    await expect(queue).toContainText("Falha no download");
    await page.getByRole("button", { name: "Tentar download novamente", exact: true }).click();
    await expect(queue).toContainText("Na fila");
    await expect(queue).not.toContainText("Falha simulada");
    await expect(queue).toContainText("25 novos importados");
    await page.screenshot({ path: "/tmp/legalos-autos-queue-ui.png", fullPage: true });
  } finally { await client.end(); }
});
