import { expect, test } from "@playwright/test";
import { PDFDocument } from "pdf-lib";
test("BOX: autos com prévia autenticada, favoritos e etapas personalizadas", async ({ page, playwright }) => {
  test.setTimeout(120_000);
  const id = Math.random().toString(36).slice(2, 10);
  await page.goto("/register");
  await page.getByLabel("Nome completo").fill(`Dona autos ${id}`);
  await page.getByLabel("E-mail").fill(`autos-${id}@example.test`);
  await page.getByLabel("Senha", { exact: true }).fill("SenhaForte123");
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await page.getByLabel("Nome do escritório").fill(`Autos ${id}`);
  await page.getByRole("button", { name: "Criar escritório", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Bom dia/ })).toBeVisible();
  await page.goto("/processos/novo");
  await page.getByLabel("Título do caso ou processo").fill(`Caso autos ${id}`);
  await page.getByRole("button", { name: "Cadastrar caso ou processo", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Caso autos ${id}`, exact: true })).toBeVisible();
  const caseUrl = page.url().split("?")[0]!;
  await page.goto(`${caseUrl}?aba=documentos`);
  const pdf = await PDFDocument.create(); pdf.addPage();
  await page.locator("#document-file").setInputFiles({ name: `sentenca-${id}.pdf`, mimeType: "application/pdf", buffer: Buffer.from(await pdf.save()) });
  await expect(page.getByRole("link", { name: `sentenca-${id}.pdf`, exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Autos digitais", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Autos digitais", exact: true })).toBeVisible();
  const iframe = page.locator("iframe");
  await expect(iframe).toHaveAttribute("src", /inline=1/);
  await page.screenshot({ path: "/tmp/legalos-box-autos.png", fullPage: true });
  const preview = await page.request.get((await iframe.getAttribute("src"))!);
  expect(preview.status()).toBe(200);
  expect(preview.headers()["content-type"]).toBe("application/pdf");
  expect(preview.headers()["content-disposition"]).toMatch(/^inline;/);
  expect(preview.headers()["x-frame-options"]).toBe("SAMEORIGIN");
  const anonymous = await playwright.request.newContext();
  const denied = await anonymous.get(new URL((await iframe.getAttribute("src"))!, page.url()).href);
  expect(denied.status()).toBe(401); await anonymous.dispose();
  await page.getByRole("button", { name: "Favoritar documento", exact: true }).click();
  await expect(page.getByRole("button", { name: "Remover favorito", exact: true })).toBeVisible();
  await page.getByLabel("Só meus favoritos").check();
  await page.getByRole("button", { name: "Buscar", exact: true }).click();
  await expect(page.getByRole("navigation", { name: "Índice dos autos" })).toContainText(`sentenca-${id}.pdf`);
  await page.goto("/tarefas/etapas");
  await page.getByRole("button", { name: "Criar etapa", exact: true }).click();
  await expect(page.getByText("Salvo.", { exact: true })).toBeVisible();
  await page.goto("/tarefas/nova");
  await page.getByLabel("Título", { exact: true }).fill(`Protocolar ${id}`);
  await page.getByRole("button", { name: "Criar tarefa", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Protocolar ${id}`, exact: true })).toBeVisible();
  await page.getByLabel("Situação da tarefa", { exact: true }).selectOption({ label: "Aguardando protocolo" });
  await expect(page.getByLabel("Situação da tarefa", { exact: true })).toHaveValue(/^stage:/);
  await expect(page.getByTestId("task-history")).toContainText("Aguardando protocolo");
  await page.goto("/box/operacao?auditar=1");
  await expect(page.getByText(/Nenhuma OAB ou conexão de tribunal cadastrada/)).toBeVisible();
  await expect(page.getByText(/0 tarefas importadas ainda abertas conferidas/)).toBeVisible();
  await page.goto("/integracoes");
  await page.getByLabel("Chave pública do DataJud", { exact: true }).fill("chave-publica-ficticia-para-teste-123");
  await page.getByRole("button", { name: "Guardar chave DataJud", exact: true }).click();
  await expect(page.getByText("Chave guardada. Teste a conexão e ligue o DataJud neste escritório.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Chave pública do DataJud", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Ligar DataJud neste escritório", exact: true }).click();
  await expect(page.getByRole("button", { name: "Desligar DataJud neste escritório", exact: true })).toBeVisible();

});
