import { expect, test } from "@playwright/test";
test("Navegação organizada, configurações por assunto e RUTE desativada", async ({ page }) => {
  const id = Math.random().toString(36).slice(2, 9);
  await page.goto("/register");
  await page.getByLabel("Nome completo").fill(`Pessoa UX ${id}`);
  await page.getByLabel("E-mail").fill(`ux-${id}@example.test`);
  await page.getByLabel("Senha", { exact: true }).fill("SenhaForte123");
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await page.getByLabel("Nome do escritório").fill(`Escritório UX ${id}`);
  await page.getByRole("button", { name: "Criar escritório", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Bom dia/ })).toBeVisible();
  const nav = page.getByRole("navigation", { name: "Navegação Evolution", exact: true });
  await nav.getByRole("button", { name: "Jurídico", exact: true }).click();
  await expect(nav.getByRole("link", { name: "Processos", exact: true })).toBeVisible();
  await expect(nav.getByRole("link", { name: "RUTE (IA)", exact: true })).toHaveCount(0);
  await expect(nav.getByRole("link", { name: "Relatórios e BI", exact: true })).toBeHidden();
  await nav.getByRole("button", { name: "Administração & Gestão", exact: true }).click();
  await nav.getByRole("link", { name: "Relatórios e BI", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Relatórios e BI", exact: true })).toBeVisible();
  await expect(nav.getByRole("button", { name: "Administração & Gestão", exact: true })).toHaveAttribute("aria-expanded", "true");
  await page.goto("/configuracoes");
  await expect(page.getByRole("heading", { name: "Escritório e equipe", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Rotina de trabalho", exact: true })).toBeVisible();
  await expect(page.getByLabel("Nome do escritório", { exact: true })).toHaveCount(0);
  await page.getByRole("searchbox", { name: "Buscar configurações", exact: true }).fill("certificado");
  await expect(page.getByRole("link", { name: /Certificados digitais/ })).toHaveCount(0);
  await expect(page.getByRole("link", { name: /^Dados do escritório/ })).toHaveCount(0);
  await page.getByRole("searchbox", { name: "Buscar configurações", exact: true }).fill("dados");
  await page.getByRole("link", { name: /^Dados do escritório/ }).click();
  await expect(page.getByLabel("Nome do escritório", { exact: true })).toHaveValue(`Escritório UX ${id}`);
  await page.getByRole("link", { name: "Todas as configurações", exact: true }).click();
  await page.getByRole("link", { name: /^Plano e uso/ }).click();
  await expect(page.getByTestId("plan-card")).toBeVisible();
  await page.goto("/configuracoes");
  await page.screenshot({ path: "/tmp/legalos-ux-settings.png", fullPage: true });
  await expect(page.getByRole("button", { name: "Abrir RUTE", exact: true })).toHaveCount(0);
  await page.goto("/rute");
  await expect(page.getByRole("heading", { name: "RUTE desativada" })).toBeVisible();
  await page.goto("/configuracoes");
  await expect(page.getByRole("link", { name: /RUTE e inteligência artificial/ })).toHaveCount(0);
  await nav.getByRole("button", { name: "Jurídico", exact: true }).click();
  await nav.getByRole("link", { name: "Processos", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Processos e casos", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Abrir menu", exact: true }).click();
  const menu = page.getByRole("dialog", { name: "Menu", exact: true });
  await expect(menu.getByRole("link", { name: "Processos", exact: true })).toBeVisible();
  await expect(menu.getByRole("link", { name: "Cálculos", exact: true })).toBeVisible();
  await page.screenshot({ path: "/tmp/legalos-ux-mobile.png", fullPage: true });
});
